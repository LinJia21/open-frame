function gitHead() {
  const child = spawnSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" });
  if (child.status !== 0) return "unavailable";
  return child.stdout.trim();
}

function printReport() {
  const ranked = [...findings].sort((left, right) => {
    const severity = SEVERITY_RANK[left.severity] - SEVERITY_RANK[right.severity];
    if (severity !== 0) return severity;
    return `${left.code}\0${left.file}\0${left.ids}`.localeCompare(`${right.code}\0${right.file}\0${right.ids}`);
  });
  const counts = { high: 0, medium: 0, low: 0, info: 0 };
  for (const finding of ranked) counts[finding.severity] += 1;
  const lines = [
    "OpenFrame demo-data audit",
    `commit: ${gitHead()}`,
    "network: not used",
    "",
    "Findings",
  ];
  if (ranked.length === 0) lines.push("(none)");
  for (const finding of ranked) {
    lines.push(`[${finding.severity}] ${finding.code}`);
    lines.push(`  file: ${finding.file}`);
    lines.push(`  ids: ${finding.ids}`);
    lines.push(`  evidence: ${finding.message}`);
    lines.push("");
  }
  lines.push("Checks that passed");
  for (const message of passes) lines.push(`PASS ${message}`);
  lines.push("");
  lines.push(`summary high=${counts.high} medium=${counts.medium} low=${counts.low} info=${counts.info}`);
  lines.push("limitations: external URLs were not requested; factual truth of LIVE articles was not judged; this script does not run Ajv or Zod (npm run validate:demo does).");
  if (counts.high + counts.medium > 0) {
    lines.push("result: high or medium findings; exit 1");
  } else {
    lines.push("result: no high or medium findings; exit 0");
  }
  process.stdout.write(`${lines.join("\n")}\n`);
  return counts.high + counts.medium > 0 ? 1 : 0;
}

function main() {
  let sample;
  let demo;
  try {
    sample = readJson("spec/data/sample-analysis-ai-animation.json");
    demo = readJson("spec/data/demo-dataset.json");
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(2);
  }
  auditBundle("spec/data/sample-analysis-ai-animation.json", sample);
  auditBundle("spec/data/demo-dataset.json", demo);
  auditCrossBundle(sample, demo);
  auditMarkdown(sample);
  auditSurfacing(sample, demo);
  auditAdjacent();
  const mock = loadMock();
  if (mock.error) {
    add("info", "MOCK_NOT_LOADED", "src/lib/analysis/cursor-fixture.ts", "bnd_mockcursor01", `the test mock could not be loaded offline: ${mock.error}`);
  } else {
    auditMock(mock.bundle);
  }
  process.exit(printReport());
}

main();
