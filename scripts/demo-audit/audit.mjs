/**
 * Offline audit of OpenFrame's pre-generated demo data.
 *
 * Run from anywhere:
 *   node scripts/demo-audit/audit.mjs
 *
 * Uses only the Node.js standard library. It does not use the network,
 * does not call a model, and does not modify the fixtures.
 *
 * Exit 0: no high or medium findings (low and info may still print).
 * Exit 1: one or more high or medium findings.
 * Exit 2: the script itself could not read a required file.
 */
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const ID_RE = /^[a-z]{2,4}_[A-Za-z0-9_-]{1,64}$/;
const RESERVED_HOST = /^(?:[^/?#:]*\.)?(?:example\.(?:com|org|net)|[a-z0-9-]+\.(?:example|test|invalid)|example|test|invalid|localhost)$/i;
const LIVE_AI_CLAIM_RE = /live[ _-]?ai|generated live|real[- ]time analysis/i;
const LIVE_AI_NEGATED_RE = /not (?:a |by a |by |produced by a |generated by a )?(?:live[ _-]?ai|generated live|real[- ]time)/i;
const SEVERITY_RANK = { high: 0, medium: 1, low: 2, info: 3 };

const findings = [];
const passes = [];

function readText(rel) {
  return readFileSync(path.join(root, rel), "utf8");
}

function readJson(rel) {
  return JSON.parse(readText(rel));
}

function add(severity, code, file, ids, message) {
  findings.push({
    severity,
    code,
    file,
    ids: Array.isArray(ids) ? ids.join(", ") : ids,
    message,
  });
}

function pass(message) {
  passes.push(message);
}

function day(value) {
  if (value == null || value === "") return null;
  return String(value).slice(0, 10);
}

function hostname(url) {
  return new URL(url).hostname.replace(/^www\./i, "").toLowerCase();
}

function isReservedUrl(url) {
  try {
    return RESERVED_HOST.test(new URL(url).hostname);
  } catch {
    return false;
  }
}

function domainMatches(domain, url) {
  if (domain == null || domain === "") return true;
  const host = hostname(url);
  const normalized = String(domain).replace(/^www\./i, "").toLowerCase();
  return host === normalized || host.endsWith(`.${normalized}`) || normalized.endsWith(`.${host}`);
}

function evidenceItems(audit) {
  return [
    ...(audit.supporting_evidence ?? []).map((item) => ({ item, side: "supporting" })),
    ...(audit.contradicting_evidence ?? []).map((item) => ({ item, side: "contradicting" })),
  ];
}

function groupCount(items) {
  return new Set(items.map((item) => item.independence_group_id)).size;
}

function sameIdSet(left, right) {
  if (left.length !== right.length) return false;
  const wanted = new Set(right);
  return left.every((id) => wanted.has(id));
}

function auditBundle(file, bundle) {
  const articles = new Map((bundle.articles ?? []).map((article) => [article.id, article]));
  const claims = bundle.claim_extraction?.claims ?? [];
  const claimById = new Map(claims.map((claim) => [claim.id, claim]));
  const audits = bundle.evidence_audit?.audits ?? [];
  const auditById = new Map(audits.map((audit) => [audit.id, audit]));
  const report = bundle.research_report ?? {};
  const narrative = bundle.narrative_comparison ?? {};
  const sources = report.source_list ?? [];
  const sourceById = new Map(sources.map((source) => [source.id, source]));
  const findingsById = new Map((report.key_findings ?? []).map((finding) => [finding.id, finding]));
  const allEvidence = audits.flatMap((audit) => evidenceItems(audit).map((entry) => entry.item));
  let broken = false;

  const noteHigh = (code, ids, message) => {
    broken = true;
    add("high", code, file, ids, message);
  };

  const definedIds = [];
  const expectId = (id, where) => {
    if (typeof id !== "string" || !ID_RE.test(id)) {
      noteHigh("ID_PATTERN", where, `id ${JSON.stringify(id)} does not match ${ID_RE}`);
      return;
    }
    definedIds.push(id);
  };

  expectId(bundle.bundle_id, "bundle_id");
  expectId(narrative.id, "narrative_comparison.id");
  expectId(bundle.claim_extraction?.id, "claim_extraction.id");
  expectId(bundle.evidence_audit?.id, "evidence_audit.id");
  expectId(report.id, "research_report.id");
  for (const article of bundle.articles ?? []) expectId(article.id, article.id ?? "article");
  for (const claim of claims) expectId(claim.id, claim.id ?? "claim");
  for (const audit of audits) expectId(audit.id, audit.id ?? "audit");
  for (const item of allEvidence) expectId(item.id, item.id ?? "evidence");
  for (const source of sources) expectId(source.id, source.id ?? "source");
  for (const finding of report.key_findings ?? []) expectId(finding.id, finding.id ?? "finding");
  for (const group of bundle.evidence_audit?.independence_groups ?? []) expectId(group.id, group.id ?? "group");

  const seen = new Set();
  for (const id of definedIds) {
    if (seen.has(id)) noteHigh("DUPLICATE_ID", id, "the same id is defined more than once in this bundle");
    seen.add(id);
  }
  const byUrl = new Map();
  for (const article of articles.values()) {
    const users = byUrl.get(article.original_url) ?? [];
    users.push(article.id);
    byUrl.set(article.original_url, users);
  }
  for (const [url, ids] of byUrl) {
    if (ids.length > 1) noteHigh("DUPLICATE_URL", ids, `these articles share original_url ${url}`);
  }

  const needArticle = (id, where) => {
    if (!articles.has(id)) noteHigh("DANGLING_ARTICLE", where, `article ${id} is not in articles[]`);
  };
  const needClaim = (id, where) => {
    if (!claimById.has(id)) noteHigh("DANGLING_CLAIM", where, `claim ${id} is not in claim_extraction.claims`);
  };

  for (const article of bundle.articles ?? []) {
    if (article.dedup?.duplicate_of != null) needArticle(article.dedup.duplicate_of, `${article.id}.dedup.duplicate_of`);
    const syndicated = article.dedup?.syndicated_from;
    if (typeof syndicated === "string" && ID_RE.test(syndicated) && !articles.has(syndicated)) {
      noteHigh("DANGLING_ARTICLE", article.id, `syndicated_from ${syndicated} is not an article id`);
    }
  }

  for (const claim of claims) needArticle(claim.article_id, `${claim.id}.article_id`);

  const auditClaimIds = [];
  for (const audit of audits) {
    auditClaimIds.push(audit.claim_id);
    needClaim(audit.claim_id, `${audit.id}.claim_id`);
    const claim = claimById.get(audit.claim_id);
    if (claim && audit.claim_text !== claim.claim_text) {
      noteHigh("CLAIM_TEXT", audit.id, "audit.claim_text differs from the claim");
    }
    for (const { item } of evidenceItems(audit)) {
      needArticle(item.article_id, `${item.id}.article_id`);
      needClaim(item.claim_id, `${item.id}.claim_id`);
      if (item.claim_id !== audit.claim_id) {
        noteHigh("EVIDENCE_CLAIM", item.id, `evidence claim_id ${item.claim_id} != audit claim_id ${audit.claim_id}`);
      }
      const article = articles.get(item.article_id);
      if (article && item.url != null && item.url !== article.original_url) {
        noteHigh("EVIDENCE_URL", item.id, `url does not equal ${article.id}.original_url`);
      }
      if (article && item.data_mode !== article.data_mode) {
        noteHigh("EVIDENCE_MODE", item.id, `data_mode ${item.data_mode} != article ${article.data_mode}`);
      }
    }
    const unverifiable = evidenceItems(audit)
      .map((entry) => entry.item)
      .filter((item) => item.quote_verification === "unverifiable")
      .map((item) => item.id)
      .sort();
    const listed = [...(audit.unverifiable_evidence_ids ?? [])].sort();
    if (JSON.stringify(unverifiable) !== JSON.stringify(listed)) {
      noteHigh("UNVERIFIABLE_LIST", audit.id, `listed ${JSON.stringify(listed)} but quote_verification marks ${JSON.stringify(unverifiable)}`);
    }
    const supporting = audit.supporting_evidence ?? [];
    const contradicting = audit.contradicting_evidence ?? [];
    if (audit.independent_source_count?.supporting !== groupCount(supporting) || audit.independent_source_count?.contradicting !== groupCount(contradicting)) {
      noteHigh(
        "INDEPENDENCE_COUNT",
        audit.id,
        `stored ${JSON.stringify(audit.independent_source_count)} but distinct groups are supporting=${groupCount(supporting)} contradicting=${groupCount(contradicting)}`,
      );
    }
    if ((audit.status === "Verified" || audit.status === "Partially Supported") && supporting.length === 0) {
      noteHigh("STATUS_EVIDENCE", audit.id, `${audit.status} has no supporting evidence`);
    }
    if ((audit.status === "Disputed" || audit.status === "Contradicted") && contradicting.length === 0) {
      noteHigh("STATUS_EVIDENCE", audit.id, `${audit.status} has no contradicting evidence`);
    }
  }
  const seenAuditClaims = new Set();
  for (const claimId of auditClaimIds) {
    if (seenAuditClaims.has(claimId)) noteHigh("DUPLICATE_AUDIT", claimId, "more than one audit points at this claim");
    seenAuditClaims.add(claimId);
  }
  for (const claim of claims) {
    if (claim.check_worthy && !seenAuditClaims.has(claim.id)) {
      noteHigh("MISSING_AUDIT", claim.id, "check_worthy claim has no audit");
    }
    if (!claim.check_worthy && seenAuditClaims.has(claim.id)) {
      add("medium", "OPINION_AUDITED", file, claim.id, "a claim with check_worthy false has an audit");
    }
  }

  const narrativeIds = new Set(narrative.article_ids ?? []);
  for (const id of narrative.article_ids ?? []) needArticle(id, `narrative_comparison.article_ids ${id}`);
  for (const analysis of narrative.article_analyses ?? []) {
    needArticle(analysis.article_id, `article_analyses ${analysis.article_id}`);
    if (!narrativeIds.has(analysis.article_id)) {
      noteHigh("NARRATIVE_MEMBERSHIP", analysis.article_id, "article analysis is not listed in narrative_comparison.article_ids");
    }
    for (const fact of analysis.source_selection?.selected_facts ?? []) {
      for (const claimId of fact.linked_claim_ids ?? []) needClaim(claimId, `${analysis.article_id} linked_claim_ids`);
    }
  }
  for (const key of ["shared_facts", "divergences"]) {
    for (const row of narrative.cross_article_comparison?.[key] ?? []) {
      for (const id of row.article_ids ?? []) needArticle(id, `cross_article_comparison.${key}`);
    }
  }
  if (report.article_comparison?.narrative_comparison_id != null && report.article_comparison.narrative_comparison_id !== narrative.id) {
    noteHigh("NARRATIVE_ID", report.id ?? file, `article_comparison.narrative_comparison_id is not ${narrative.id}`);
  }
  for (const row of report.article_comparison?.rows ?? []) {
    needArticle(row.article_id, `article_comparison.rows ${row.article_id}`);
    const article = articles.get(row.article_id);
    if (article && row.publisher !== article.publisher?.name) {
      add("medium", "ROW_PUBLISHER", file, row.article_id, `row publisher ${JSON.stringify(row.publisher)} != ${JSON.stringify(article.publisher?.name)}`);
    }
  }
  for (const event of report.topic_background?.timeline ?? []) {
    for (const sourceId of event.source_ids ?? []) {
      if (!sourceById.has(sourceId)) noteHigh("TIMELINE_SOURCE", sourceId, `timeline source_id is not in source_list (${event.date})`);
    }
  }
  for (const source of sources) {
    needArticle(source.article_id, `${source.id}.article_id`);
    const article = articles.get(source.article_id);
    if (!article) continue;
    if (source.url !== article.original_url) noteHigh("SOURCE_URL", source.id, `source_list url != ${article.id}.original_url`);
    if (source.data_mode !== article.data_mode) noteHigh("SOURCE_MODE", source.id, `source_list data_mode != ${article.id}.data_mode`);
    if (source.title !== article.title) {
      add("low", "SOURCE_TITLE", file, `${article.id}, ${source.id}`, `titles differ: ${JSON.stringify(article.title)} vs ${JSON.stringify(source.title)}`);
    }
  }
  for (const row of report.key_claim_verification ?? []) {
    const audit = auditById.get(row.audit_id);
    const claim = claimById.get(row.claim_id);
    if (!audit) noteHigh("KCV_AUDIT", row.audit_id ?? "missing", "key_claim_verification audit_id does not resolve");
    if (!claim) noteHigh("KCV_CLAIM", row.claim_id ?? "missing", "key_claim_verification claim_id does not resolve");
    needArticle(row.article_id, `key_claim_verification ${row.claim_id}`);
    if (audit && audit.claim_id !== row.claim_id) noteHigh("KCV_CLAIM", row.audit_id, `row claim_id ${row.claim_id} != audit claim_id ${audit.claim_id}`);
    if (claim && claim.article_id !== row.article_id) noteHigh("KCV_ARTICLE", row.claim_id, `row article_id ${row.article_id} != claim article_id ${claim.article_id}`);
    if (audit && audit.status !== row.status) noteHigh("KCV_STATUS", row.audit_id, `row status ${row.status} != audit status ${audit.status}`);
    if (audit && audit.confidence?.level !== row.confidence_level) {
      noteHigh("KCV_CONFIDENCE", row.audit_id, `row confidence ${row.confidence_level} != audit ${audit.confidence?.level}`);
    }
  }
  const kcvAudits = (report.key_claim_verification ?? []).map((row) => row.audit_id);
  for (const audit of audits) {
    if (!kcvAudits.includes(audit.id)) noteHigh("KCV_COVERAGE", audit.id, "audit is missing from key_claim_verification");
  }
  const seenKcv = new Set();
  for (const auditId of kcvAudits) {
    if (seenKcv.has(auditId)) noteHigh("KCV_DUPLICATE", auditId, "key_claim_verification repeats this audit");
    seenKcv.add(auditId);
  }
  for (const finding of report.key_findings ?? []) {
    for (const claimId of finding.claim_ids ?? []) needClaim(claimId, `${finding.id}.claim_ids`);
    for (const auditId of finding.audit_ids ?? []) {
      if (!auditById.has(auditId)) noteHigh("FINDING_AUDIT", finding.id, `unknown audit ${auditId}`);
    }
    const covered = (finding.audit_ids ?? []).map((auditId) => auditById.get(auditId)?.claim_id).filter(Boolean);
    if (!sameIdSet(finding.claim_ids ?? [], covered)) {
      noteHigh("FINDING_AUDIT", finding.id, `audit_ids cover ${JSON.stringify(covered)} but claim_ids are ${JSON.stringify(finding.claim_ids)}`);
    }
  }
  for (const findingId of report.executive_summary?.finding_ids ?? []) {
    if (!findingsById.has(findingId)) noteHigh("SUMMARY_FINDING", findingId, "executive_summary.finding_ids does not resolve");
  }

  checkSpans(file, bundle, articles, noteHigh);
  if (!broken) {
    pass(`linkage ${file}: articles=${articles.size} claims=${claims.length} audits=${audits.length} evidence=${allEvidence.length} sources=${sources.length} findings=${report.key_findings?.length ?? 0}; ids, references, spans, and copied statuses resolve`);
  }
  auditProvenance(file, bundle);
  auditQuality(file, bundle, articles, claims, audits);
}

function checkSpans(file, bundle, articles, noteHigh) {
  const check = (articleId, text, span, id, what) => {
    const article = articles.get(articleId);
    if (!article?.accessible_text || text == null) {
      noteHigh("SPAN", id, `${what} is marked verified_substring but the cited article has no accessible_text`);
      return;
    }
    const generatedOnLive = article.accessible_text_origin === "generated_demo" && bundle.data_mode === "LIVE";
    if (article.accessible_text_origin === "search_snippet" || generatedOnLive) {
      noteHigh("SPAN", id, `${what} is a verified substring of origin ${article.accessible_text_origin}`);
    }
    if (!span) {
      noteHigh("SPAN", id, `${what} is verified_substring without a span`);
      return;
    }
    const slice = article.accessible_text.slice(span.start, span.end);
    if (slice !== text) noteHigh("SPAN", id, `${what} != ${articleId}.accessible_text.slice(${span.start}, ${span.end})`);
  };
  for (const audit of bundle.evidence_audit?.audits ?? []) {
    for (const { item } of evidenceItems(audit)) {
      if (item.quote_verification === "verified_substring") check(item.article_id, item.excerpt, item.excerpt_span, item.id, "excerpt");
    }
  }
  for (const claim of bundle.claim_extraction?.claims ?? []) {
    if (!claim.is_verbatim) continue;
    const article = articles.get(claim.article_id);
    if (!article?.accessible_text?.includes(claim.claim_text)) {
      noteHigh("VERBATIM_CLAIM", claim.id, "is_verbatim claim_text is not an exact substring of the article accessible_text");
    }
  }
  for (const analysis of bundle.narrative_comparison?.article_analyses ?? []) {
    for (const quote of analysis.source_selection?.quoted_voices ?? []) {
      if (quote.quote_verification === "verified_substring") {
        check(analysis.article_id, quote.verbatim_quote, quote.quote_span, `${analysis.article_id}:${quote.speaker}`, "quoted voice");
      }
    }
  }
}

function partsOf(bundle) {
  return [
    ["bundle", bundle],
    ["narrative_comparison", bundle.narrative_comparison],
    ["claim_extraction", bundle.claim_extraction],
    ["evidence_audit", bundle.evidence_audit],
    ["research_report", bundle.research_report],
  ];
}

function auditProvenance(file, bundle) {
  const generation = bundle.analysis_generation;
  let provenanceOk = true;
  const fail = (severity, code, ids, message) => {
    provenanceOk = false;
    add(severity, code, file, ids, message);
  };
  if (generation !== "PRECOMPUTED") fail("high", "NOT_PRECOMPUTED", bundle.bundle_id, `analysis_generation is ${JSON.stringify(generation)}`);
  for (const [name, part] of partsOf(bundle).slice(1)) {
    if (part?.analysis_generation !== generation) {
      fail("high", "GENERATION_MISMATCH", name, `${name}.analysis_generation is ${JSON.stringify(part?.analysis_generation)}, bundle is ${JSON.stringify(generation)}`);
    }
  }
  const notice = bundle.data_mode_notice ?? "";
  if (!notice) fail("high", "MISSING_NOTICE", bundle.bundle_id, "data_mode_notice is empty");
  if (generation === "PRECOMPUTED" && LIVE_AI_CLAIM_RE.test(notice) && !LIVE_AI_NEGATED_RE.test(notice)) {
    fail("high", "NOTICE_CLAIMS_LIVE", bundle.bundle_id, `PRECOMPUTED notice claims a live analysis: ${notice}`);
  }
  const generator = bundle.research_report?.metadata?.generator ?? "";
  if (LIVE_AI_CLAIM_RE.test(generator) && !LIVE_AI_NEGATED_RE.test(generator)) {
    fail("high", "GENERATOR_CLAIMS_LIVE", bundle.bundle_id, `generator text claims a live analysis: ${generator}`);
  }
  const versions = new Set();
  const walkVersion = (value) => {
    if (!value || typeof value !== "object") return;
    if (!Array.isArray(value) && typeof value.schema_version === "string") versions.add(value.schema_version);
    for (const child of Object.values(value)) walkVersion(child);
  };
  walkVersion(bundle);
  const unexpected = [...versions].filter((version) => version !== "1.2.0");
  if (unexpected.length > 0) fail("high", "SCHEMA_VERSION", bundle.bundle_id, `schema_version values other than 1.2.0: ${unexpected.join(", ")}`);

  const recordModes = new Set();
  for (const article of bundle.articles ?? []) recordModes.add(article.data_mode);
  for (const claim of bundle.claim_extraction?.claims ?? []) recordModes.add(claim.data_mode);
  for (const audit of bundle.evidence_audit?.audits ?? []) {
    recordModes.add(audit.data_mode);
    for (const { item } of evidenceItems(audit)) recordModes.add(item.data_mode);
  }
  if (bundle.data_mode === "LIVE" && recordModes.has("DEMO")) fail("high", "MODE_MIX", bundle.bundle_id, "LIVE bundle contains DEMO records");
  if (bundle.data_mode === "DEMO" && recordModes.has("LIVE")) fail("high", "MODE_MIX", bundle.bundle_id, "DEMO bundle contains LIVE records");
  if (bundle.research_report?.metadata?.data_mode !== bundle.data_mode) {
    fail("high", "MODE_MIX", bundle.bundle_id, "research_report.metadata.data_mode differs from the bundle");
  }

  const warnings = bundle.research_report?.metadata?.warnings ?? [];
  const demoWarning = warnings.some((warning) => warning.code === "DEMO_DATA");
  if (bundle.data_mode === "DEMO" && !demoWarning) fail("high", "MISSING_DEMO_WARNING", bundle.bundle_id, "DEMO bundle has no DEMO_DATA warning");
  if (bundle.data_mode === "LIVE" && demoWarning) fail("high", "LIVE_DEMO_WARNING", bundle.bundle_id, "LIVE bundle carries a DEMO_DATA warning");

  for (const article of bundle.articles ?? []) {
    const fictional = article.publisher?.fictional_demo_publisher === true;
    if (article.data_mode === "DEMO" && !fictional) fail("high", "PUBLISHER_FLAG", article.id, "DEMO article does not set fictional_demo_publisher true");
    if (article.data_mode === "LIVE" && fictional) fail("high", "PUBLISHER_FLAG", article.id, "LIVE article sets fictional_demo_publisher true");
    if (article.data_mode === "LIVE" && (article.retrieval_method === "generated_demo" || article.accessible_text_origin === "generated_demo")) {
      fail("high", "LIVE_GENERATED_DEMO", article.id, "LIVE article uses generated_demo retrieval or origin");
    }
    if (article.data_mode === "DEMO" && article.retrieval_method !== "generated_demo") {
      fail("medium", "DEMO_RETRIEVAL", article.id, `DEMO article retrieval_method is ${article.retrieval_method}`);
    }
    try {
      const reserved = isReservedUrl(article.original_url);
      if (article.data_mode === "DEMO" && !reserved) fail("high", "DEMO_URL", article.id, `DEMO url is not on a reserved host: ${article.original_url}`);
      if (article.data_mode === "LIVE" && reserved) fail("high", "LIVE_URL", article.id, `LIVE url is on a reserved host: ${article.original_url}`);
    } catch {
      fail("high", "BAD_URL", article.id, `original_url is not a URL: ${article.original_url}`);
    }
    if (article.publisher?.domain && article.original_url) {
      try {
        if (!domainMatches(article.publisher.domain, article.original_url)) {
          fail("medium", "PUBLISHER_DOMAIN", article.id, `publisher.domain ${article.publisher.domain} does not match ${article.original_url}`);
        }
      } catch {
        fail("high", "BAD_URL", article.id, `original_url is not a URL: ${article.original_url}`);
      }
    }
    const provenance = article.provenance;
    if (provenance) {
      if (provenance.data_mode !== article.data_mode) fail("high", "PROVENANCE_MODE", article.id, "provenance.data_mode differs from the article");
      if (provenance.retrieval_method !== article.retrieval_method) fail("medium", "PROVENANCE_METHOD", article.id, "provenance.retrieval_method differs from the article");
    }
  }

  if (provenanceOk && versions.size > 0) {
    pass(`provenance ${file}: data_mode=${bundle.data_mode} analysis_generation=${generation} schema=${[...versions].join(",")}`);
  }
}

function auditQuality(file, bundle, articles, claims, audits) {
  const report = bundle.research_report ?? {};
  const coveredClaims = new Set((report.key_findings ?? []).flatMap((finding) => finding.claim_ids ?? []));
  const missingFromFindings = claims.filter((claim) => claim.check_worthy && !coveredClaims.has(claim.id)).map((claim) => claim.id);
  if (missingFromFindings.length > 0) {
    add(
      "low",
      "CLAIM_NOT_IN_FINDINGS",
      file,
      missingFromFindings,
      "these check-worthy claims have audits and key_claim_verification rows, but no key_findings[].claim_ids entry. The executive summary can still mention the subject without a finding id.",
    );
  }

  for (const claim of claims) {
    const audit = audits.find((item) => item.claim_id === claim.id);
    const evidenceCount = audit ? evidenceItems(audit).length : 0;
    if (claim.check_worthy && audit && evidenceCount === 0) {
      add("info", "CLAIM_WITHOUT_EVIDENCE", file, claim.id, `${claim.assertion_kind} claim is check_worthy and audited as ${audit.status}, with zero supporting or contradicting evidence. The 1.2.0 contract allows that for Unverified.`);
    }
    if (!claim.check_worthy && !audit) {
      add("info", "OPINION_NOT_AUDITED", file, claim.id, `${claim.assertion_kind} claim has check_worthy false and no audit. The contract says opinions are not audited.`);
    }
  }

  const doubled = (report.key_claim_verification ?? []).filter((row) => typeof row.one_line_explanation === "string" && row.one_line_explanation.endsWith("..")).map((row) => row.audit_id);
  if (doubled.length > 0) {
    add("low", "DOUBLE_PERIOD", file, doubled, "key_claim_verification.one_line_explanation ends with two periods. The matching audit.explanation ends with one period; the row adds another.");
  }

  for (const article of bundle.articles ?? []) {
    for (const shared of article.dedup?.shared_original_sources ?? []) {
      if (shared.url && shared.url === article.original_url && shared.independence_group_id === article.dedup?.independence_group_id) {
        add("low", "SELF_SHARED_SOURCE", file, article.id, `shared_original_sources repeats this article's own url and independence group (${shared.independence_group_id}): ${shared.url}`);
      }
    }
  }

  const declaredOrigin = (bundle.evidence_audit?.missing_fields ?? []).some((field) => String(field.field).includes("origin_url"));
  for (const group of bundle.evidence_audit?.independence_groups ?? []) {
    if (group.origin_url == null && !declaredOrigin) {
      add("low", "GROUP_ORIGIN_UNLISTED", file, group.id, "independence group origin_url is null and evidence_audit.missing_fields does not list origin_url. Article-level nulls in this bundle are listed in missing_fields.");
    }
  }

  const window = report.metadata?.coverage_window;
  if (window?.from && window?.to) {
    const outside = [];
    for (const article of articles.values()) {
      const published = day(article.publication_date);
      if (published && (published < window.from || published > window.to)) outside.push(`${article.id} ${published}`);
    }
    if (outside.length > 0) {
      add("medium", "COVERAGE_WINDOW", file, outside.map((item) => item.split(" ")[0]), `coverage_window is ${window.from} to ${window.to}, which does not include ${outside.join("; ")}.`);
    }
  }

  const small = (report.metadata?.warnings ?? []).find((warning) => warning.code === "SMALL_SAMPLE");
  if (small) {
    const analysed = [...articles.values()].filter((article) => article.analysis_role === "analysed");
    const match = /^(\d+)\s+fictional articles\.?$/.exec(small.message);
    if (match && Number(match[1]) === analysed.length && articles.size !== analysed.length) {
      const evidenceOnly = articles.size - analysed.length;
      add("low", "SMALL_SAMPLE_COUNT", file, bundle.bundle_id, `SMALL_SAMPLE says "${small.message}" The bundle has ${articles.size} articles: ${analysed.length} analysed and ${evidenceOnly} evidence_only. The number matches the analysed subset only, and the sentence does not say so.`);
    }
    const publishers = new Set(analysed.map((article) => article.publisher.name));
    const variety = analysed.filter((article) => article.publisher.name === "Variety").length;
    const evidenceOnly = [...articles.values()].filter((article) => article.analysis_role === "evidence_only").length;
    if (small.message.includes("analysed articles")) {
      const expected = `${analysed.length} analysed articles from ${publishers.size} publishers (${variety} from Variety) plus ${evidenceOnly} evidence-only`;
      if (!small.message.startsWith(expected)) {
        add("medium", "SMALL_SAMPLE_COUNT", file, bundle.bundle_id, `SMALL_SAMPLE text does not match the articles. Computed: ${expected}. Stored: ${small.message}`);
      } else {
        pass(`counts ${file}: SMALL_SAMPLE matches ${analysed.length} analysed, ${publishers.size} publishers, ${variety} Variety, ${evidenceOnly} evidence-only`);
      }
    }
  }

  const snippetWarning = (report.metadata?.warnings ?? []).find((warning) => warning.code === "SNIPPET_ONLY_SOURCES");
  const snippets = [...articles.values()].filter((article) => article.accessible_text_origin === "search_snippet" || article.retrieval_method === "web_search_snippet");
  if (snippetWarning) {
    const uncovered = snippets.filter((article) => !snippetWarningMentions(snippetWarning.message, article.publisher.name));
    if (uncovered.length > 0) {
      add("medium", "SNIPPET_WARNING", file, uncovered.map((article) => article.id), `SNIPPET_ONLY_SOURCES does not mention ${uncovered.map((article) => article.publisher.name).join(", ")}`);
    } else {
      pass(`counts ${file}: SNIPPET_ONLY_SOURCES covers ${snippets.length} snippet articles`);
    }
  } else if (snippets.length > 0) {
    add("medium", "SNIPPET_WARNING", file, snippets.map((article) => article.id), "snippet articles exist but there is no SNIPPET_ONLY_SOURCES warning");
  }

  const httpUrls = new Map();
  const remember = (url, id) => {
    if (typeof url === "string" && url.startsWith("http://")) {
      const users = httpUrls.get(url) ?? [];
      users.push(id);
      httpUrls.set(url, users);
    }
  };
  for (const article of articles.values()) {
    remember(article.original_url, article.id);
    for (const shared of article.dedup?.shared_original_sources ?? []) remember(shared.url, article.id);
  }
  for (const claim of claims) remember(claim.original_source_hint?.url, claim.id);
  for (const group of bundle.evidence_audit?.independence_groups ?? []) remember(group.origin_url, group.id);
  for (const audit of audits) {
    remember(audit.original_source_url, audit.id);
    for (const { item } of evidenceItems(audit)) remember(item.url, item.id);
  }
  for (const source of report.source_list ?? []) remember(source.url, source.id);
  for (const [url, ids] of httpUrls) {
    let truncated = false;
    try {
      truncated = new URL(url).pathname.endsWith("-");
    } catch {
      truncated = false;
    }
    const article = [...articles.values()].find((item) => item.original_url === url);
    const title = article?.title ?? "";
    add(
      "medium",
      truncated ? "TRUNCATED_CITATION_URL" : "HTTP_CITATION_URL",
      file,
      [...new Set(ids)],
      truncated
        ? `stored citation uses http and the path ends with a hyphen: ${url}. The stored title continues past that slug: ${JSON.stringify(title)}. The same string is reused by ${[...new Set(ids)].join(", ")}. This audit did not request the URL, so it does not say whether a publisher page exists at that exact address.`
        : `stored citation uses http while the other stored article URLs in this bundle use https: ${url}. Not requested.`,
    );
  }
}

function snippetWarningMentions(message, publisher) {
  const text = message.toLowerCase();
  const name = publisher.toLowerCase();
  if (text.includes(name)) return true;
  if (name.includes("animation guild") && text.includes("tag")) return true;
  if (name.includes("amazon") && text.includes("amazon")) return true;
  if (name.includes("disney") && text.includes("disney")) return true;
  if (name.includes("bloomberg") && text.includes("bloomberg")) return true;
  return false;
}

function labelGaps(bundle) {
  const gaps = [];
  if (bundle.data_mode !== "DEMO") return gaps;
  for (const article of bundle.articles ?? []) {
    if (!/\(fictional\)\s*$/i.test(article.publisher?.name ?? "")) {
      gaps.push(`${article.id} publisher.name ${JSON.stringify(article.publisher?.name)} does not end with (fictional)`);
    }
    if (!String(article.title ?? "").startsWith("[DEMO — fictional]")) {
      gaps.push(`${article.id} title has no [DEMO — fictional] prefix`);
    }
  }
  const notice = bundle.data_mode_notice ?? "";
  if (!/pre-?generated|PRECOMPUTED/i.test(notice)) gaps.push(`data_mode_notice does not say the analysis is pre-generated: ${JSON.stringify(notice)}`);
  const reportId = bundle.research_report?.id ?? "";
  if (!reportId.startsWith("rep_")) gaps.push(`research_report.id ${reportId} does not use the documented rep_ prefix`);
  return gaps;
}

function auditCrossBundle(sample, demo) {
  const owners = new Map();
  const collect = (file, bundle) => {
    const walk = (value) => {
      if (!value || typeof value !== "object") return;
      if (!Array.isArray(value) && typeof value.id === "string" && ID_RE.test(value.id)) {
        const files = owners.get(value.id) ?? new Set();
        files.add(file);
        owners.set(value.id, files);
      }
      for (const child of Object.values(value)) walk(child);
    };
    walk(bundle);
  };
  collect("spec/data/sample-analysis-ai-animation.json", sample);
  collect("spec/data/demo-dataset.json", demo);
  const collisions = [...owners.entries()].filter(([, files]) => files.size > 1).map(([id]) => id);
  if (collisions.length > 0) {
    add("high", "CROSS_BUNDLE_ID", "spec/data", collisions, "the same record id is defined in both served bundles");
  } else {
    pass("cross-bundle ids: the two served bundles do not share a record id");
  }
}

function auditMarkdown(sample) {
  const file = "spec/sample-analysis-ai-animation.md";
  const markdown = readText(file);
  const missingUrls = [];
  for (const article of sample.articles) {
    if (!markdown.includes(article.original_url)) missingUrls.push(article.id);
  }
  const missingFindings = (sample.research_report.key_findings ?? []).filter((finding) => !markdown.includes(finding.statement)).map((finding) => finding.id);
  const missingWarnings = (sample.research_report.metadata.warnings ?? []).filter((warning) => !markdown.includes(warning.message)).map((warning) => warning.code);
  const summary = sample.research_report.executive_summary?.text ?? "";
  const summaryMissing = summary && !markdown.includes(summary);
  if (missingUrls.length || missingFindings.length || missingWarnings.length || summaryMissing) {
    add(
      "medium",
      "MARKDOWN_DRIFT",
      file,
      [...missingUrls, ...missingFindings, ...missingWarnings],
      `readable sample differs from the JSON. Missing urls: ${missingUrls.join(", ") || "none"}. Missing findings: ${missingFindings.join(", ") || "none"}. Missing warnings: ${missingWarnings.join(", ") || "none"}. Executive summary present: ${summaryMissing ? "no" : "yes"}.`,
    );
  } else if (!/PRE-GENERATED ANALYSIS/.test(markdown) || !/REAL SOURCES/.test(markdown)) {
    add("medium", "MARKDOWN_LABEL", file, "sample-analysis-ai-animation.md", "the readable sample does not carry both the REAL SOURCES and PRE-GENERATED ANALYSIS labels");
  } else {
    pass("markdown spec/sample-analysis-ai-animation.md: every article URL, finding statement, warning, and the executive summary match the JSON, and the header says REAL SOURCES and PRE-GENERATED ANALYSIS");
  }
}

function auditSurfacing(sample, demo) {
  const catalog = readText("src/lib/demo/catalog.ts");
  const readme = readText("README.md");
  const dataset = readText("spec/data/demo-dataset.json");
  const retired = ["Northlight Studios", "Coastal Courier", "The Lantern Review"];
  const present = retired.filter((name) => (catalog.includes(name) || readme.includes(name)) && !dataset.includes(name));
  if (present.length > 0) {
    add(
      "medium",
      "STALE_DEMO_LABEL",
      "src/lib/demo/catalog.ts",
      present,
      `${present.join(", ")} is still used as a current label, and it does not appear in spec/data/demo-dataset.json. catalog.ts preparedTopics title and selectFixture still key the fictional bundle on "northlight". README.md presents "Northlight Studios fictional demonstration" as the second suggestion that opens that file. spec/README.md records the rename Northlight Studios → Plumvale Toonworks, Coastal Courier → Brackenmoor Courier, The Lantern Review → The Quillowick Review. The test src/lib/analysis/analyses-http.test.ts still posts the Northlight query.`,
    );
  }

  const fixtureIds = readText("src/lib/analysis/fixture-ids.ts");
  const sampleVersion = sample.schema_version;
  const demoVersion = demo.schema_version;
  if (fixtureIds.includes("1.1.0") && sampleVersion === "1.2.0" && demoVersion === "1.2.0") {
    add("low", "FIXTURE_VERSION_COMMENT", "src/lib/analysis/fixture-ids.ts", "bnd_ai_animation_2026, bnd_demo_ai_animation", `the comment calls these "vendored 1.1.0 fixtures", but both JSON files declare schema_version ${sampleVersion}.`);
  }

  const settings = readText("src/app/settings/page.tsx");
  const feed = readText("src/lib/home/feed.ts");
  if (settings.includes("主张计数") && feed.includes("evidence_audit.audits")) {
    const describe = (bundle) => {
      const opinions = (bundle.claim_extraction.claims ?? []).filter((claim) => !claim.check_worthy).map((claim) => claim.id);
      return `${bundle.bundle_id}: ${bundle.claim_extraction.claims.length} claims, ${bundle.evidence_audit.audits.length} audits, opinions omitted ${opinions.join(", ") || "none"}`;
    };
    add("low", "SETTINGS_COUNT_LABEL", "src/app/settings/page.tsx", "bnd_ai_animation_2026, bnd_demo_ai_animation", `the settings page labels the status histogram 主张计数. src/lib/home/feed.ts builds statusCounts from evidence_audit.audits, not from claims. ${describe(sample)}. ${describe(demo)}.`);
  }

  const officialGaps = labelGaps(demo);
  if (officialGaps.length > 0) {
    add("medium", "DEMO_LABEL_GAP", "spec/data/demo-dataset.json", "bnd_demo_ai_animation", officialGaps.join(" | "));
  } else {
    pass("labels spec/data/demo-dataset.json: DEMO, fictional_demo_publisher, (fictional) publisher names, [DEMO — fictional] titles, PRE-GENERATED notice, DEMO_DATA warning");
  }
  const liveNotice = sample.data_mode_notice ?? "";
  if (sample.data_mode === "LIVE" && /PRE-GENERATED|PRECOMPUTED/i.test(liveNotice) && /LIVE|REAL SOURCE/i.test(liveNotice)) {
    pass("labels spec/data/sample-analysis-ai-animation.json: LIVE sources, fictional_demo_publisher false, notice says REAL SOURCES and PRE-GENERATED ANALYSIS");
  }

  if (feed.includes('sampleKind: "layout-sample"') && feed.includes("虚构")) {
    pass('labels src/lib/home/feed.ts: the third card is sampleKind layout-sample, has a null bundle id, and its title says 虚构');
  } else {
    add("medium", "LAYOUT_SAMPLE_LABEL", "src/lib/home/feed.ts", "layout-sample", "the fictional layout card is missing its 虚构 title or layout-sample kind");
  }
}

